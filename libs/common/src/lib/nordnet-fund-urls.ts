/** Normalizes a fund name the same way the map keys were built. */
export function normalizeFundName(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

/** Resolves a Nordnet fund URL path by (fuzzy) fund name, or null. */
export function nordnetUrlForName(name: string): string | null {
  const key = normalizeFundName(name);
  if (NORDNET_FUND_URLS[key]) {
    return NORDNET_FUND_URLS[key];
  }
  // Fallback: a stored key that starts with the query (share-class suffix
  // differences like trailing 'a'/'c'/'sek').
  for (const storedKey of Object.keys(NORDNET_FUND_URLS)) {
    if (storedKey.startsWith(key) || key.startsWith(storedKey)) {
      return NORDNET_FUND_URLS[storedKey];
    }
  }
  return null;
}
